"""Reproduce synthetic data, trained models, charts, and held-out metrics."""
import json
from pathlib import Path
import numpy as np
from src.pipeline import ROOT, generate, split_participants, train_branch, save_model


def svg_bar(path, title, labels, values, colors, y_label):
    width, height = 700, 390
    top, bottom = 70, 315
    maximum = max(values) * 1.18 or 1
    bars = []
    for i,(label,value,color) in enumerate(zip(labels,values,colors)):
        x = 82 + i * (530/len(values)) + 25
        bw = 530/len(values)-50
        h = value/maximum*(bottom-top)
        bars.append(f'<rect x="{x:.1f}" y="{bottom-h:.1f}" width="{bw:.1f}" height="{h:.1f}" rx="9" fill="{color}"/><text x="{x+bw/2:.1f}" y="{bottom-h-12:.1f}" text-anchor="middle" font-size="17" font-weight="700" fill="#172430">{value:.2f}</text><text x="{x+bw/2:.1f}" y="347" text-anchor="middle" font-size="14" fill="#526172">{label}</text>')
    svg=f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}"><rect width="100%" height="100%" fill="#f8fafb"/><text x="40" y="38" font-family="Arial" font-size="22" font-weight="700" fill="#172430">{title}</text><line x1="82" y1="315" x2="635" y2="315" stroke="#b9c8d0"/><text x="20" y="200" transform="rotate(-90 20 200)" font-family="Arial" font-size="14" fill="#526172">{y_label}</text><g font-family="Arial">{''.join(bars)}</g></svg>'''
    path.write_text(svg)


def main():
    assets=ROOT/'assets'; assets.mkdir(exist_ok=True)
    df=generate()
    df.to_csv(ROOT/'data'/'synthetic_repetitions.csv',index=False)
    splits=split_participants(df)
    velocity=train_branch(df,False,splits)
    combined=train_branch(df,True,splits)
    save_model(ROOT/'models'/'velocity.json',velocity,False)
    save_model(ROOT/'models'/'combined.json',combined,True)
    summary={"source":"SYNTHETIC, generated by src/pipeline.py; these are not research results",
             "participants":len(df.participant.unique()),"sets":len(df.set_id.unique()),"repetitions":len(df),
             "split_participants":splits,
             "velocity_only":velocity['metrics'],"velocity_plus_candidate_tremor":combined['metrics'],
             "relative_MAE_change_percent":round(100*(velocity['metrics']['MAE']-combined['metrics']['MAE'])/velocity['metrics']['MAE'],1),
             "epochs":{"velocity_only":velocity['epochs'],"combined":combined['epochs']}}
    (ROOT/'metrics.json').write_text(json.dumps(summary,indent=2))
    svg_bar(assets/'rir_distribution.svg','Synthetic RIR label distribution', [str(x) for x in range(0,14)],
            [int((df.rir==x).sum()) for x in range(0,14)], ['#18a999']*14,'Repetitions')
    svg_bar(assets/'feature_means.svg','Features by RIR band', ['Velocity / m/s','Tremor × 3'],
            [round(df[df.rir<=2].velocity.mean(),2),round(df[df.rir<=2].tremor_amplitude.mean()*3,2)],
            ['#316da8','#ed915b'],'Illustrative mean')
    svg_bar(assets/'model_mae.svg','Held-out participant MAE', ['Velocity','Velocity + tremor'],
            [velocity['metrics']['MAE'],combined['metrics']['MAE']],['#316da8','#18a999'],'RIR repetitions')
    print(json.dumps(summary,indent=2))


if __name__=='__main__': main()
